# 资金流强度：钱还在不在往这个池子流
#
# 来源是一份实盘 LP 分享，核心那句是"我不看 APR 还有多高，我看钱还在不在往这个方向流"。
# APR 是历史快照，5 分钟成交量才是当下的真实状态。一个池子的 5 分钟成交开始萎缩，
# 手续费就在快速消失，而仪表板上的 APR 还会挂着漂亮数字骗你留在里面。
#
# 做法：把 5 分钟成交换算成小时速率，和过去一小时的实际速率比。
#   比值 > 1 说明当下比过去一小时更热，资金在涌入
#   比值 < 1 说明在退潮，手续费收入正在往下走

# 5 分钟折算成小时要乘的倍数
M5_TO_HOUR = 12

# 资金流分档
SURGE = 2.0      # 当下速率是过去一小时的两倍以上，正在爆发
STEADY = 0.6     # 0.6 到 2 之间算正常
FADING = 0.3     # 低于 0.6 是退潮，低于 0.3 是快没了


def strength(r):
    m5 = r.get("vol_5m", 0.0)
    h1 = r.get("vol_1h", 0.0)
    if h1 <= 0:
        return None
    now_rate = m5 * M5_TO_HOUR
    return now_rate / h1


def grade(r):
    s = strength(r)
    if s is None:
        return "未知", "拿不到 5 分钟数据，无法判断当下资金流", 1

    if s >= SURGE:
        return "涌入", f"当下成交速率是过去一小时的 {s:.1f} 倍，资金正在涌入", 2
    if s >= STEADY:
        return "正常", f"当下速率与过去一小时相当（{s:.1f} 倍），资金流稳定", 2
    if s >= FADING:
        return "退潮", f"当下速率只有过去一小时的 {s:.1f} 倍，成交在萎缩，手续费会跟着掉", 1
    return "枯竭", f"当下速率仅为过去一小时的 {s:.1f} 倍，成交几乎停了，留在池子里只剩风险", 0


