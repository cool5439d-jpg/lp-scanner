# 时点评级：数字合格不等于现在该进场
#
# 硬性淘汰线管的是"这个池能不能做"，时点管的是"现在该不该做"。
# SHROOM 就是典型：24h 跌 5.3% 没触发 -20% 的淘汰线，但 6h 跌 6.4%、1h 跌 5.8%，
# 跌势在加速，进场就是用 USDG 一路接越来越便宜的币。
#
# 判据是三个周期的相对关系，不是单看 24h 幅度。

# 加速下跌：短周期跌幅超过长周期，说明还在往下砸
ACCEL_DUMP_1H = -3.0
ACCEL_DUMP_6H = -4.0

# 加速上涨：同理，暴涨途中做市会在半山腰把币卖光
ACCEL_PUMP_1H = 4.0
ACCEL_PUMP_6H = 6.0

# 下跌判据：6h 跌超这个数才算"在跌"，配合 1h 是否转正区分企稳与未止
DIP_6H = -4.0

# 走平判据：三个周期都在这个带内，说明价格稳住了
CALM_BAND = 2.0

# 涨势衰竭（见顶滞涨）：长周期暴涨但短周期已经涨不动了
# UBIK 的实测读数：1h +0.7%、6h +47%、24h +25.4%。六小时涨幅比一整天还大，
# 说明这波拉升几乎全在最近六小时，而最近一小时只剩 0.7%，已经滞涨。
# 原来的加速上涨判据要求 1h 涨超 4%，正好被这种形态躲过去，是规则的真实缺口。
EXHAUST_6H = 15.0        # 6h 至少涨这么多才谈得上"拉升"
EXHAUST_RATIO = 1.3      # 6h 涨幅超过 24h 的这个倍数，说明涨全在最近
EXHAUST_1H = 2.0         # 而 1h 已经低于这个数，动能耗尽


def grade(r):
    h1, h6, h24 = r["chg_1h"], r["chg_6h"], r["chg_24h"]

    # 跌势加速：1h 跌幅接近或超过 6h，说明砸盘还在进行
    if h1 <= ACCEL_DUMP_1H and h6 <= ACCEL_DUMP_6H and h1 <= h6 / 2:
        return "差", f"跌势加速（1h {h1:+.1f}% / 6h {h6:+.1f}%），进场是接刀"

    # 涨势加速：暴涨途中进场，仓位会在上涨中把币不断卖出
    if h1 >= ACCEL_PUMP_1H and h6 >= ACCEL_PUMP_6H:
        return "差", f"涨势加速（1h {h1:+.1f}% / 6h {h6:+.1f}%），会在半山腰卖光"

    # 涨势衰竭：6h 暴涨、涨幅集中在最近、但 1h 已经停滞，是拉到顶部滞涨的形态
    # 进这种池大概率遇到回落，在下跌途中一路接盘
    if h6 >= EXHAUST_6H and h6 > h24 * EXHAUST_RATIO and h1 < EXHAUST_1H:
        return "差", (f"涨势衰竭（6h {h6:+.1f}% 大于 24h {h24:+.1f}%，说明涨幅全在最近；"
                     f"而 1h 只剩 {h1:+.1f}%，动能已尽），大概率回落，进场是接盘")

    # 单边下跌但已减速：1h 明显好于 6h，跌势在缓
    if h6 <= DIP_6H and h1 > 0:
        return "尚可", f"跌后企稳（6h {h6:+.1f}% 但 1h {h1:+.1f}%），可小仓试探"

    # 跌了但还没转正：方向未定，不能因为跌幅不够大就当成震荡放行
    # 这条必须排在震荡判据前面。否则 1h -0.5% / 6h -6% 这种"仍在跌"的形态
    # 会掉进下面宽松的震荡兜底被判成"好"，评级反而高于真正企稳的池子。
    if h6 <= DIP_6H and h1 <= 0:
        return "尚可", f"跌势未止（6h {h6:+.1f}%，1h {h1:+.1f}% 仍未转正），方向未定，等企稳再进"

    # 三个周期都平稳，最适合做市
    if all(abs(x) <= CALM_BAND for x in (h1, h6, h24)):
        return "好", "三个周期都平稳，适合中性做市"

    # 震荡：有涨有跌但幅度可控，做市最舒服的行情
    if abs(h24) <= 15 and abs(h1) <= 6:
        return "好", f"震荡行情（24h {h24:+.1f}%），做市能反复吃到手续费"

    return "尚可", f"波动偏大（1h {h1:+.1f}% / 6h {h6:+.1f}% / 24h {h24:+.1f}%），仓位放小"


# 时点差的池子，仓位打折
SIZE_FACTOR = {"好": 1.0, "尚可": 0.5, "差": 0.25}
