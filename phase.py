# 代币生命周期分段，以及每个阶段对应的布局打法
#
# 来源是一份实盘 LP 分享，它把 meme 币拆成拉升、横盘、崩盘三个阶段，
# 每个阶段用完全不同的形状和区间。这比单纯给一个"时点好坏"有用得多，
# 因为它直接回答了"现在该怎么摆流动性"。
#
# 底层逻辑就一句：价格接下来往哪走，我的流动性在不在它经过的路上。
# 只有价格在你的区间里穿梭时才收得到手续费。
#
# 分段依据是价格走势加资金流，两者缺一不可：
#   光看价格涨会把"拉升"和"反弹后见顶"混为一谈
#   光看资金流会把"横盘但成交活跃"误判成拉升

import flow
import fomo_flow


# 5 分钟涨幅超过这个数，说明当下正在回升，不该再算作"还在崩"
REBOUND_5M = 2.0


def detect(r):
    h1, h6, h24 = r["chg_1h"], r["chg_6h"], r["chg_24h"]
    m5 = r.get("chg_5m", 0.0)
    fg, _, _ = flow.grade(r)

    # 1h/6h/24h 都是滚动窗口，拿现在和 N 小时前比。价格刚从底部拉起来时，
    # 这些窗口仍是深负，但当下其实已经在涨。CME 实测 5m +6.3% 而 1h -27%，
    # 只看 1h 会把刚反弹的判成还在崩盘。所以先看 5 分钟。
    if m5 >= REBOUND_5M and h24 <= -20:
        return "反弹", (f"深跌后当下正在回升（5 分钟 {m5:+.1f}%，而 1 小时窗口仍显示 {h1:+.1f}%），"
                       f"方向尚未确认"), "小仓试探，宽区间"

    # 崩盘：单边下跌且资金在撤。这个阶段做 LP 是纯送死，
    # 成交没了收不到手续费，价格单边跌会把 USDG 持续换成这个币，跌多少就承担多少
    if h6 <= -12 and h1 <= 0 and fg in ("退潮", "枯竭"):
        return "崩盘", "叙事结束，价格单边下跌且成交萎缩", "不做，撤"

    if h24 <= -25 and h1 <= -3:
        return "崩盘", "深跌且仍在往下，接刀风险极高", "不做，撤"

    # 拉升：价格阶梯往上且资金涌入。手续费最肥但也最容易吃亏
    if h1 >= 3 and h6 >= 8 and fg in ("涌入", "正常"):
        return "拉升", "价格快速上行且成交活跃，手续费最肥的阶段", "偏上方多段，窄区间"

    # 见顶：涨幅集中在过去但当下已停滞，是拉升的尾声
    if h6 >= 15 and h1 < 2:
        return "见顶", "涨幅集中在前几小时，当下已滞涨，随时回落", "不做，等回调站稳"

    # 横盘：波动收敛且成交没死。这是性价比最高的阶段
    if abs(h1) <= 4 and abs(h6) <= 10 and fg in ("涌入", "正常", "退潮"):
        return "横盘", "价格在区间内反复，狙击盘已走，剩真实交易者", "集中在震荡核心区"

    # 反弹：跌完开始回升
    if h6 <= -6 and h1 > 2:
        return "反弹", "急跌后开始回升，方向尚未确认", "小仓试探，宽区间"

    return "不明", f"形态不清晰（1h {h1:+.1f}% / 6h {h6:+.1f}% / 24h {h24:+.1f}%）", "谨慎，宽区间小仓"


