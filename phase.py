# 阶段对应的仓位系数
SIZE_FACTOR = {"拉升": 0.8, "横盘": 1.0, "反弹": 0.5, "见顶": 0.25, "崩盘": 0.0, "不明": 0.5}


# 按阶段给区间：拉升期上方留更多空间，其余对称
def range_for(ph, base_pct):
    if ph == "拉升":
        return -int(base_pct * 0.6), int(base_pct * 1.6)
    if ph == "崩盘" or ph == "见顶":
        return -int(base_pct * 1.5), int(base_pct * 1.5)
    return -base_pct, base_pct


# 撤退信号：三种状态通用，中两个减仓，中三个清仓
def exit_signals(r):
    sig = []
    fg, fnote, _ = flow.grade(r)
    # 退潮若是聪明钱卖出压下来的，成交量本身可能还稳，"成交萎缩"这条就不对；下面"聪明钱离场"会单独报
    if fg in ("退潮", "枯竭") and fomo_flow.adjust(r) >= 0:
        sig.append(f"成交萎缩：{fnote}")
    if r["chg_1h"] <= -5:
        sig.append(f"价格急跌：1 小时 {r['chg_1h']:+.1f}%")
    if r["chg_6h"] <= -15:
        sig.append(f"中期破位：6 小时 {r['chg_6h']:+.1f}%")
    if r["trades_24h"] < 2000:
        sig.append(f"交易稀疏：日笔数仅 {r['trades_24h']}")
    # 榜单交易员在卖：你已经在池里时最该怕的一条
    smart_exit = fomo_flow.exit_signal(r)
    if smart_exit:
        sig.append(smart_exit)
    return sig
